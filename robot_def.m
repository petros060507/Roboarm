function robot = robot_def()
% ROBOT_DEF  Возвращает структуру с параметрами 6-DOF роборуки.
%
%   Поля структуры:
%     DH          — матрица DH-параметров [n x 4]: [a, alpha, d, theta_off]
%     n           — число степеней свободы
%     mass        — масса каждого звена [1 x n], кг
%     com         — положение CoM в СК звена [n x 3], м
%     payload_mass    — масса нагрузки на фланце, кг
%     payload_com     — CoM нагрузки в СК последнего звена [1 x 3], м
%     k_dyn       — коэффициент динамического запаса (>=1)
%     g           — вектор гравитации в мировой СК [3 x 1], м/с²
%     joint_tau_max   — максимальный момент привода [1 x n], Н·м
%     joint_names     — имена суставов (cell array)
%
%   Геометрия соответствует условному 6-осевому манипулятору
%   с вертикальной первой осью (схожему с UR-серией).

    % ── DH-параметры ─────────────────────────────────────────────────────
    %   строка i:  [a_i,  alpha_i,  d_i,  theta_off_i]
    %   theta_i = theta_off_i + q_i  (q_i — переменная сустава)
    robot.DH = [
        0,       pi/2,    0.1625,  0;      % joint 1  (вращение вокруг Z base)
        -0.425,  0,       0,       0;      % joint 2
        -0.3922, 0,       0,       0;      % joint 3
        0,       pi/2,    0.1333,  0;      % joint 4
        0,      -pi/2,    0.0997,  0;      % joint 5
        0,       0,       0.0996,  0;      % joint 6
    ];

    robot.n = size(robot.DH, 1);   % 6

    % ── Масса звеньев [кг] ───────────────────────────────────────────────
    robot.mass = [3.761, 8.058, 2.846, 1.37, 1.3, 0.365];

    % ── CoM каждого звена в его собственной СК [м] ───────────────────────
    %   Знак и направление подобраны под условный манипулятор
    robot.com = [
         0,        -0.02,    0;        % звено 1 (почти на оси)
         0.2125,    0,       0.138;    % звено 2 (вдоль a2)
         0.1961,    0,       0.0165;   % звено 3
         0,        -0.0093,  0;        % звено 4
         0,         0.0093,  0;        % звено 5
         0,         0,      -0.026;    % звено 6 (фланец)
    ];

    % ── Нагрузка на фланце ────────────────────────────────────────────────
    robot.payload_mass = 2.0;               % кг
    robot.payload_com  = [0, 0, 0.05];      % м  в СК joint 6

    % ── Динамический запас ───────────────────────────────────────────────
    % τ_required = k_dyn · τ_static
    % Выбирается исходя из ожидаемых ускорений:
    %   1.0 → чисто статика   1.3 → умеренная динамика   1.6 → высокая
    robot.k_dyn = 1.3;

    % ── Гравитация ────────────────────────────────────────────────────────
    robot.g = [0; 0; -9.81];              % [м/с²] мировая СК (Z вверх)

    % ── Паспортные максимальные моменты приводов [Н·м] ───────────────────
    robot.joint_tau_max = [330, 330, 150, 54, 54, 54];

    % ── Имена суставов ────────────────────────────────────────────────────
    robot.joint_names = {'J1 (Waist)', 'J2 (Shoulder)', 'J3 (Elbow)', ...
                         'J4 (Wrist1)', 'J5 (Wrist2)', 'J6 (Wrist3)'};
end
