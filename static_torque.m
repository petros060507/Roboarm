function [tau_static, tau_req, util, p_com_w] = static_torque(robot, q)
% STATIC_TORQUE  Вычисляет статические моменты во всех суставах.
%
%   [tau_static, tau_req, util, p_com_w] = static_torque(robot, q)
%
%   Входные аргументы:
%     robot   — структура из robot_def()
%     q       — вектор углов суставов [1 x n] или [n x 1], рад
%
%   Выходные аргументы:
%     tau_static  — статический момент [n x 1], Н·м
%     tau_req     — требуемый момент с запасом k_dyn [n x 1], Н·м
%     util        — коэффициент использования привода [n x 1], 0..1+
%     p_com_w     — позиции CoM всех тел в мировой СК [3 x (n+1)]
%                   последний столбец — CoM нагрузки
%
%   Метод: принцип виртуальной мощности (якобиановый подход).
%
%     τ_i = Σ_{j=i}^{N}  z_i · (r_{i→com_j} × F_g_j)
%
%   где:
%     z_i     — единичный вектор оси вращения сустава i в мировой СК
%     r_{i→j} — вектор от начала сустава i до CoM тела j
%     F_g_j   — сила тяжести тела j = m_j * g
%     N       — число тел (n звеньев + 1 нагрузка)

    q = q(:);
    n = robot.n;
    g = robot.g;           % [3 x 1]

    % ── Прямая кинематика ─────────────────────────────────────────────────
    T = forward_kinematics(robot.DH, q);
    %   T{1}    = eye(4)  (база)
    %   T{i+1}  = трансформация до конца звена i

    % ── Позиции CoM в мировой СК ─────────────────────────────────────────
    %   Тела: звенья 1..n + нагрузка (индекс n+1)
    N_bodies = n + 1;
    p_com_w  = zeros(3, N_bodies);
    mass_all = [robot.mass(:)', robot.payload_mass];   % [1 x N_bodies]

    for i = 1:n
        % CoM звена i в мировой СК =
        %   origin звена i  +  R_{0,i} * com_local_i
        p_com_w(:, i) = T{i+1}(1:3, 4) + ...
                        T{i+1}(1:3, 1:3) * robot.com(i, :)';
    end
    % Нагрузка — CoM в СК последнего звена
    p_com_w(:, n+1) = T{n+1}(1:3, 4) + ...
                      T{n+1}(1:3, 1:3) * robot.payload_com(:);

    % ── Оси вращения и начала суставов в мировой СК ──────────────────────
    %   Сустав i описывается трансформацией T{i}  (СК *перед* суставом i)
    z_w = zeros(3, n);   % оси z
    o_w = zeros(3, n);   % начала суставов

    for i = 1:n
        z_w(:, i) = T{i}(1:3, 3);   % третий столбец = z_{i-1}
        o_w(:, i) = T{i}(1:3, 4);
    end

    % ── Расчёт τ_static ───────────────────────────────────────────────────
    tau_static = zeros(n, 1);

    for i = 1:n
        % Сустав i нагружен весами всех тел j >= i
        % (тела с меньшим индексом "ниже" по кинематической цепи
        %  и не создают момента в суставе i)
        for j = i:N_bodies
            F_g = mass_all(j) * g;                    % [3 x 1] сила тяжести тела j
            r   = p_com_w(:, j) - o_w(:, i);         % вектор сустав i → CoM j

            % Момент = проекция на ось вращения:
            %   τ_i += z_i · (r × F_g)
            tau_static(i) = tau_static(i) + dot(z_w(:, i), cross(r, F_g));
        end
    end

    % ── Требуемый момент с коэффициентом динамического запаса ────────────
    tau_req = robot.k_dyn * tau_static;

    % ── Коэффициент использования привода ────────────────────────────────
    %   util > 1 означает перегрузку привода
    util = abs(tau_req) ./ robot.joint_tau_max(:);
end
